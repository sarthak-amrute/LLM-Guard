"""
Adapter for Google Gemini API.
Uses official google.genai SDK or direct Google AI Studio REST endpoints.
"""

import time
import requests
from typing import Tuple, Optional, Dict, Any
from .base import BaseTargetAdapter


class GeminiAdapter(BaseTargetAdapter):
    """
    Adapter communicating with Google Gemini API.
    Supports gemini-2.5-flash, gemini-2.5-pro, gemini-1.5-flash, etc.
    """

    def __init__(self, config: Dict[str, Any]):
        super().__init__(config)
        self.model = self.model or "gemini-3.5-flash-lite"
        self._sdk_client = None


        if self.api_key:
            try:
                from google import genai
                self._sdk_client = genai.Client(api_key=self.api_key)
            except Exception:
                self._sdk_client = None

    def _call_via_rest(self, prompt: str, system_prompt: Optional[str] = None, max_tokens: Optional[int] = None) -> Tuple[str, Optional[int]]:
        """Fallback direct REST call to Google Generative Language API."""
        if not self.api_key:
            return "[ERROR] Gemini API key not provided.", None

        # Clean model name (strip "models/" prefix if user included it)
        clean_model = self.model.replace("models/", "")
        endpoint = f"https://generativelanguage.googleapis.com/v1beta/models/{clean_model}:generateContent?key={self.api_key}"

        body: Dict[str, Any] = {
            "contents": [
                {
                    "parts": [{"text": prompt}]
                }
            ]
        }

        generation_config: Dict[str, Any] = {}
        if max_tokens:
            generation_config["maxOutputTokens"] = max_tokens
        if generation_config:
            body["generationConfig"] = generation_config

        eff_sys = self.get_effective_system_prompt(system_prompt)
        if eff_sys:
            body["systemInstruction"] = {
                "parts": [{"text": eff_sys}]
            }

        t0 = time.monotonic()
        try:
            resp = requests.post(endpoint, json=body, timeout=self.timeout)
            latency_ms = round((time.monotonic() - t0) * 1000)

            if resp.status_code == 200:
                data = resp.json()
                candidates = data.get("candidates", [])
                if candidates:
                    parts = candidates[0].get("content", {}).get("parts", [])
                    if parts and "text" in parts[0]:
                        return parts[0]["text"], latency_ms
                return "[No textual output generated by model]", latency_ms

            err_data = resp.json().get("error", {})
            err_msg = err_data.get("message", resp.text)
            status_code = resp.status_code

            if status_code == 400:
                return f"[ERROR] Invalid request or unsupported model '{self.model}': {err_msg}", latency_ms
            elif status_code == 403 or status_code == 401:
                return f"[ERROR] Gemini Authentication failed (HTTP {status_code}): Invalid API key or permission denied.", latency_ms
            elif status_code == 429:
                return f"[ERROR] Gemini Quota/Rate limit exceeded (HTTP 429): {err_msg}", latency_ms
            return f"[ERROR] Gemini API error (HTTP {status_code}): {err_msg}", latency_ms

        except requests.exceptions.Timeout:
            return f"[ERROR] Gemini request timed out after {self.timeout}s.", None
        except requests.exceptions.RequestException as exc:
            return f"[ERROR] Gemini network error: {self.sanitize_error(exc)}", None

    def _call_via_sdk(self, prompt: str, system_prompt: Optional[str] = None, max_tokens: Optional[int] = None) -> Tuple[str, Optional[int]]:
        """Call Gemini using the official google.genai SDK."""
        from google.genai import types

        eff_sys = self.get_effective_system_prompt(system_prompt)
        config_kwargs: Dict[str, Any] = {
            "automatic_function_calling": types.AutomaticFunctionCallingConfig(disable=True)
        }
        if eff_sys:
            config_kwargs["system_instruction"] = eff_sys
        if max_tokens:
            config_kwargs["max_output_tokens"] = max_tokens

        config = types.GenerateContentConfig(**config_kwargs)


        t0 = time.monotonic()
        try:
            clean_model = self.model.replace("models/", "")
            response = self._sdk_client.models.generate_content(
                model=clean_model,
                contents=prompt,
                config=config
            )
            latency_ms = round((time.monotonic() - t0) * 1000)

            text = getattr(response, "text", None)
            if not text and hasattr(response, "candidates") and response.candidates:
                first_cand = response.candidates[0]
                if hasattr(first_cand, "content") and first_cand.content and first_cand.content.parts:
                    text = first_cand.content.parts[0].text

            return text or "[No response text generated]", latency_ms

        except Exception as exc:
            # Fall back to REST if SDK throws configuration or version mismatch error
            clean_err = self.sanitize_error(exc)
            return f"[ERROR] Gemini SDK call failed: {clean_err}", None

    def test_connection(self) -> Tuple[bool, str, Optional[int]]:
        """Verify API key validity and model access with a minimal ping prompt."""
        if not self.api_key:
            return False, "Gemini API key is required.", None

        t0 = time.monotonic()
        # Use a short ping
        ping_prompt = "Say 'OK' to confirm connectivity."
        resp, lat = self.send_message(ping_prompt, system_prompt=None)

        if resp.startswith("[ERROR]"):
            return False, resp.replace("[ERROR] ", ""), lat

        latency = lat if lat is not None else round((time.monotonic() - t0) * 1000)
        return True, f"Successfully connected to Gemini model '{self.model}'", latency

    def send_message(self, prompt: str, system_prompt: Optional[str] = None) -> Tuple[str, Optional[int]]:
        """Send prompt to Gemini model using SDK or REST fallback."""
        if not self.api_key:
            return "[ERROR] Gemini API key is missing.", None

        if self._sdk_client:
            res, lat = self._call_via_sdk(prompt, system_prompt)
            if not res.startswith("[ERROR]"):
                return res, lat
            # If SDK returned an error, attempt REST once
            return self._call_via_rest(prompt, system_prompt)

        return self._call_via_rest(prompt, system_prompt)
